export function getGlyph(character: string, context: string): Glyph {
  const value = GLYPHS[character];
  if (!value) {
    throw new Error(`Unsupported handwriting character ${JSON.stringify(character)} in ${context}. Add an original glyph to marker-glyphs.ts.`);
  }
  return value;
}
